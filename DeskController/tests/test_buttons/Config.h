// =====================================================================
//  Compile-time pin check: fails the build if any pin above is
//  reserved on the WROVER-E, is a strapping pin, is used twice, or if
//  a pin needing an output or a pull-up lands on an input-only pin.
// =====================================================================
namespace pincheck {
  constexpr bool forbidden(uint8_t p) {
    return (p >= 6 && p <= 11) || p == 16 || p == 17 ||          // flash, PSRAM
           p == 1 || p == 3 ||                                    // UART0
           p == 0 || p == 2 || p == 5 || p == 12 || p == 15 ||    // strapping
           p > 39 || p == 20 || p == 24 || (p >= 28 && p <= 31) || p == 37 || p == 38;
  }
  constexpr bool inputOnly(uint8_t p) { return p >= 34 && p <= 39; }

  // every pin in use in the selected configuration
  constexpr uint8_t USED[] = {
    LEG_PINS[0].encA, LEG_PINS[0].encB, LEG_PINS[1].encA, LEG_PINS[1].encB,
    LEG_PINS[2].encA, LEG_PINS[2].encB, LEG_PINS[3].encA, LEG_PINS[3].encB,
    PIN_BTN_UP, PIN_BTN_DOWN, PIN_PRESET_ADC,
    PIN_DISP_CLK, PIN_DISP_DIO, PIN_MOTOR_POWER,
    PIN_I2C_SDA, PIN_I2C_SCL,
  };
  constexpr size_t N = sizeof(USED) / sizeof(USED[0]);

  constexpr bool allAllowed(size_t i = 0) {
    return i >= N || ((USED[i] == PIN_NONE || !forbidden(USED[i])) && allAllowed(i + 1));
  }
  constexpr bool noDupFrom(size_t i, size_t j) {
    return j >= N || ((USED[i] == PIN_NONE || USED[i] != USED[j]) && noDupFrom(i, j + 1));
  }
  constexpr bool noDuplicates(size_t i = 0) {
    return i >= N || (noDupFrom(i, i + 1) && noDuplicates(i + 1));
  }
  constexpr bool outputsOk() {
    return !inputOnly(PIN_BTN_UP) && !inputOnly(PIN_BTN_DOWN)       // need internal pull-ups
        && !inputOnly(PIN_DISP_CLK) && !inputOnly(PIN_DISP_DIO)     // display outputs
        && !inputOnly(PIN_MOTOR_POWER)
        && !inputOnly(PIN_I2C_SDA) && !inputOnly(PIN_I2C_SCL)
        ;
  }
  static_assert(NUM_LEGS == 4, "pin check assumes 4 legs; update USED[] if you change NUM_LEGS");
  static_assert(allAllowed(),   "A pin is reserved on the WROVER-E (flash/PSRAM/UART) or is a strapping pin");
  static_assert(noDuplicates(), "The same GPIO is assigned twice");
  static_assert(PIN_PRESET_ADC >= 32 && PIN_PRESET_ADC <= 39,
                "Preset ladder must be on an ADC1 pin (32-39); ADC2 stops working when Wi-Fi is on");
  static_assert(outputsOk(),    "An output or pulled-up input is on an input-only pin (34-39)");
}
