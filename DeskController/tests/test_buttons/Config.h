#pragma once
#include <Arduino.h>

// ---------------------------------------------------------------------
//  Leg count
// ---------------------------------------------------------------------
#define NUM_LEGS 4

// ---------------------------------------------------------------------
//  Target: ESP32-WROVER-E module
//  (Arduino IDE board: "ESP32 Wrover Module" or "ESP32 Dev Module" with
//   PSRAM enabled)
// ---------------------------------------------------------------------
#if defined(CONFIG_IDF_TARGET) && !defined(CONFIG_IDF_TARGET_ESP32)
  #error "This pin map is for the ESP32-WROVER-E (original ESP32 chip). Select an ESP32 (not S2/S3/C3) board."
#endif

// ---------------------------------------------------------------------
//  Encoder backend
//    1 = ESP32 hardware pulse counter (PCNT). Counts in hardware with a
//        glitch filter and zero CPU load. The ESP32 has 8 units; we use 4.
//    0 = GPIO interrupt decoder (fallback; also used automatically on
//        Arduino-ESP32 core 2.x)
// ---------------------------------------------------------------------
#define ENCODER_USE_PCNT 1

// Glitch filter for PCNT, in nanoseconds (max ~12700 on ESP32). Pulses
// shorter than this are ignored. Motor brush noise lives here.
#define ENCODER_GLITCH_NS 1000

// =====================================================================
//  PIN MAP — ESP32-WROVER-E
//  Full wiring diagram: docs/wiring_diagram.png (generated by
//  docs/make_wiring_diagram.py; re-run it if you change pins here).
//
//  Off-limits on this module, and enforced by the check at the bottom
//  of this file:
//    GPIO 6–11      internal SPI flash
//    GPIO 16, 17    internal PSRAM (WROVER only)
//    GPIO 1, 3      USB serial (UART0 TX/RX)
//    GPIO 0,2,5,12,15  boot strapping pins
//
//  That leaves 17 clean GPIOs:
//    4 13 14 18 19 21 22 23 25 26 27 32 33 34 35 36 39
//
//  Used                                         Spare (clean)
//    Encoders  13 25 26 32 34 35 36 39 (8)        4 14
//    Buttons   18 19                   (2)
//    Presets   33 (R-2R ladder, ADC1)  (1)
//    I2C       21 22                   (2)
//    Display   23 (CLK) 27 (DIO)       (2)
//
//  The preset ladder must be on an ADC1 pin (32–39). ADC2 can't be read
//  while Wi-Fi is running. All the ADC1 pins were encoders, so leg 2's
//  encoder B moved from 33 to 13 (any GPIO works for an encoder).
//
//  Encoder notes:
//   * 34/35/36/39 are input-only and have NO internal pull-ups. Fit
//     external pull-ups to 3.3V (2.2k–4.7k) on ALL eight encoder lines.
//     Desk-leg hall sensors are often 5V open-collector: pull up to 3.3V,
//     NOT 5V. If they push-pull at 5V, level-shift them.
//   * GPIO 36/39 have a chip erratum: a brief ~80 ns low glitch when
//     ADC1 or Wi-Fi powers up. The 1 µs PCNT glitch filter removes it.
//     Keep the PCNT backend if you add Wi-Fi later.
// =====================================================================
struct LegPins {
  uint8_t encA, encB;   // quadrature inputs
};

static constexpr LegPins LEG_PINS[NUM_LEGS] = {
  // encA encB
  {  34,  35 },   // leg 0  front-left
  {  36,  39 },   // leg 1  front-right
  {  32,  13 },   // leg 2  rear-left   (B moved off 33 for the preset ladder)
  {  25,  26 },   // leg 3  rear-right
};

// Per-leg direction DEFAULTS. You normally don't edit these: run the
// "calib" serial command once after wiring up. It works out each leg's
// motor and encoder direction, saves them to flash, and loads them at
// every boot. These values are only used until then, or after
// "calib reset".
static const bool MOTOR_INVERT[NUM_LEGS]   = { false, false, false, false };
static const bool ENCODER_INVERT[NUM_LEGS] = { false, false, false, false };

// Hand-held buttons (active LOW, to GND, internal pull-ups enabled)
#define PIN_BTN_UP    18
#define PIN_BTN_DOWN  19

// ---------------------------------------------------------------------
//  Preset buttons: 4 buttons, one ADC pin, 4-bit R-2R ladder
//  (schematic: docs/preset_ladder.png)
//
//            2R          R           R           R
//   GND ───/\/\───┬───/\/\───┬───/\/\───┬───/\/\───┬───┬── GPIO 33
//    (terminator) │           │           │           │   │
//                 2R          2R          2R          2R  ═╧═ 100nF to GND
//                 │           │           │           │      (noise filter)
//                 b0          b1          b2          b3
//               (P4)        (P3)        (P2)        (P1)
//
//   Each bN node: 1k to GND, and the button from bN to 3.3V.
//   Suggested: R = 10k, 2R = 20k (or 2x 10k in series).
//
//   Ideal output with one button held: P1 = 1/2 x 3.3V = 1.65V,
//   P2 = 0.82V, P3 = 0.41V, P4 = 0.21V, none = 0V. The 1k pull-downs and
//   resistor tolerance shift these a few %, so run "btncal" once and the
//   real levels are saved to flash. P1 gets the biggest step, so wire your
//   most-used preset there.
//
//   Short press  = go to that preset
//   Hold 2 s     = save the current height to that preset ("S n" on display)
//   Any press during an automatic move stops it.
// ---------------------------------------------------------------------
#define PIN_PRESET_ADC        33
#define PRESET_LONG_PRESS_MS 2000
#define PRESET_SUPPLY_MV     3300    // ladder reference (the 3.3V the buttons switch)

// I2C bus to the BTS7960 board (its qwiic connector: 1 GND, 2 3.3V, 3 SDA, 4 SCL).
// The ESP32 must supply 3.3V on pin 2: it powers the ISO1540's ESP32 side.
#define PIN_I2C_SDA   21
#define PIN_I2C_SCL   22

#define PIN_NONE 255          // "no pin" marker (e.g. PIN_MOTOR_POWER unused)

// Gotek LEDC68 3-digit LED display (TM1651). 2-wire, NOT I2C, so it
// needs its own pins. Power the board from 3.3V.
#define PIN_DISP_CLK  23
#define PIN_DISP_DIO  27


// ---------------------------------------------------------------------
//  Display behaviour
// ---------------------------------------------------------------------
#define DISPLAY_TIMEOUT_MS     5000   // dark after this long with no button/serial input
#define DISPLAY_BRIGHTNESS        5   // 0 (dim) .. 7 (bright)
#define DISPLAY_INCHES            0   // 0 = show height in cm, 1 = whole inches
#define DISPLAY_MSG_MS         1200   // how long "P 1" / "S 1" messages show
// Motion counts as activity, so the display stays lit for the whole move
// and goes dark DISPLAY_TIMEOUT_MS after the desk stops.
// A fault always wakes the display. Set this to 1 to keep a fault showing
// until it is cleared, instead of timing out like normal.
#define DISPLAY_FAULT_STAYS_ON    0

// ---------------------------------------------------------------------
//  Mechanics
// ---------------------------------------------------------------------
// Encoder counts per mm of leg travel (all 4 edges counted, i.e. 4x the
// encoder's pulses per revolution). Measure it: home, move up, measure
// how far the desk moved, divide the counts by the mm.
#define COUNTS_PER_MM       40.0f

#define MIN_HEIGHT_MM        2.0f    // relative to the homed bottom (stay off the hard stop)
#define MAX_HEIGHT_MM      600.0f    // soft upper limit
#define HEIGHT_OFFSET_MM   620.0f    // desk height at the bottom (display only)

// ---------------------------------------------------------------------
//  Motion profile
// ---------------------------------------------------------------------
#define MAX_SPEED_MM_S      35.0f    // cruise speed
#define ACCEL_MM_S2         60.0f    // ramp rate (soft start and stop)
#define HOMING_SPEED_MM_S   12.0f    // slow, so the end-stop stall is gentle
#define HOMING_BACKOFF_MM    3.0f    // back off the end stop after homing

#define CONTROL_HZ         200       // control loop rate

// ---------------------------------------------------------------------
//  Per-leg position controller (output is -1.0 .. +1.0 motor command)
//    out = FF * (v / vmax)  +  KP * err  +  KI * ∫err
//  The error is in mm. Start with KI = 0 and raise KP until the legs
//  track well without buzzing, then add a little KI.
// ---------------------------------------------------------------------
#define KFF                 0.80f    // feed-forward: duty at cruise speed
#define KP                  0.15f    // per mm of error
#define KI                  0.40f    // per mm*s of error
#define I_LIMIT             0.30f    // anti-windup clamp on the integral term
#define MIN_DUTY            0.08f    // dead-band compensation (motor stiction)
#define POSITION_TOL_MM     0.5f     // "arrived" tolerance
#define SETTLE_TIMEOUT_MS  1000      // stop trying to settle after this long
#define OUTPUT_SLEW_PER_S    4.0f    // max duty change per second (0->100% in 250 ms)

// ---------------------------------------------------------------------
//  Motor driver: "i2c BTS7960" board (PCA9685 + 8x BTS7960B, ISO1540)
// ---------------------------------------------------------------------

// PCA9685 address = 0x40 + jumpers. JP1..JP6 close A0..A5 (+1 +2 +4 +8
// +16 +32). All open = 0x40. Your old library defaulted to 0x60 (JP6
// closed). If you're unsure, the boot log scans the bus and lists
// what it finds.
#define BTS_BOARD_ADDR    0x40

// PCA9685 PWM frequency. Its hardware maximum is ~1526 Hz, so the motors
// will whine audibly. The BTS7960 could do 25 kHz, but the PCA9685 can't.
#define BTS_PWM_HZ        1526

// Which board port (1..4, as silk-screened / as in your library) each
// leg is plugged into. Port 1 = J5 pins 1-2, 2 = J5 3-4, 3 = J3 1-2,
// 4 = J3 3-4 (J2/J4 screw terminals are in parallel).
static const uint8_t LEG_PORT[NUM_LEGS] = { 1, 2, 3, 4 };

// I2C clock. The board has 10k pull-ups on the ESP32 (side 1) of the
// ISO1540. That's too weak for a clean 400 kHz and below the ISO1540's
// 0.5 mA minimum sink current. Add 2.2k–4.7k pull-ups to 3.3V at the
// ESP32, or drop this to 100000 if you see Er4 / I2C errors.
#define I2C_FREQ_HZ     400000

// Optional hardware kill: a GPIO that switches the board's 24 V supply
// (relay or MOSFET module, active HIGH = power on). The PCA9685 keeps
// driving the motors if the ESP32 hangs, reboots, or loses the I2C cable;
// this is the only way to stop them then. Spare clean pins: 4, 14.
#ifndef PIN_MOTOR_POWER
#define PIN_MOTOR_POWER   PIN_NONE
#endif

// ---------------------------------------------------------------------
//  Synchronization and safety
// ---------------------------------------------------------------------
// The shared setpoint may never lead the slowest leg by more than this.
// A slow leg makes the whole desk wait for it.
#define MAX_LEAD_MM          4.0f

// If any two legs ever differ by more than this, stop everything.
#define SYNC_FAULT_MM       10.0f

// Stall: commanded above STALL_DUTY but moved less than STALL_MIN_MM in
// STALL_TIME_MS. Means an obstruction or an end stop. Fault, or end of
// homing for that leg.
#define STALL_DUTY           0.25f
#define STALL_MIN_MM         0.3f
#define STALL_TIME_MS      400

// Encoder sanity check: faster than this means noise or a wiring fault.
#define MAX_PLAUSIBLE_MM_S 120.0f

// Save the position to flash when stopped, so the desk need not re-home
// after every power cycle.
#define PERSIST_POSITION     1

#define NUM_PRESETS          4

